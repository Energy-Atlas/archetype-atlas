"""Write the evidence-only comparison of the IECC commercial family with the 90.1 templates (ADR 0040 item 11).

python -m scripts.iecc_commercial_review            # write docs/reviews/iecc-commercial-vs-90-1.md
python -m scripts.iecc_commercial_review --check    # rebuild and compare

Compares, per building type, IECC 2009 / 2015 / 2021 with 90.1-2007 / 2013 / 2019, the
editions of comparable vintage. It is evidence only: it creates no pairing and no shared
records. Program densities of both families are weighted by the IECC zone floor areas
of the same space types; envelope values are the 5A contexts' exterior wall, roof and
window assemblies by area-dominant building default.
"""
import argparse
import json
import math
from collections import defaultdict

from scripts.common import ROOT, load_json
from scripts.iecc_commercial_zones import TYPES

OUTPUT = ROOT/'docs/reviews/iecc-commercial-vs-90-1.md'
PAIRS = (('2009', '90.1-2007'), ('2015', '90.1-2013'), ('2021', '90.1-2019'))
QUANTITIES = (('lighting', 'LPD W/m²'), ('electric_equipment', 'EPD W/m²'), ('occupancy', 'person/100 m²'))


def ninety_one():
    """{(template, building type, program name): {quantity: value}} from release 1.2.0's source programs."""
    from scripts import atlas_minor_release
    out = {}
    for path, data in atlas_minor_release.files('1.2.0').items():
        if '/programs/source/' not in path or not path.startswith('commercial/90-1-'):
            continue
        p = json.loads(data)
        values = {}
        for load in p['loads']:
            value = load.get('value')
            if value is None and 'filling' in load:
                value = load['filling']['set'].get('value')
            values[load['quantity']] = value
        lighting = values.get('lighting')
        if lighting is not None and values.get('additional_lighting'):
            values['lighting'] = lighting + values['additional_lighting']
        out[(p['template'], p['building_type'], p['name'])] = values
    return out


def weighted(programs, values, quantity):
    total = area = 0.0
    for p in programs:
        v = values(p).get(quantity)
        a = math.fsum(z['floor_area_m2']*z['multiplier'] for z in p['source_zones'] if z['counted'])
        if v is None or a == 0:
            continue
        total += v*a
        area += a
    return total/area if area else None


def envelope(payload):
    """5A exterior wall and roof layer U (no films) and window U/SHGC of the building-default assemblies."""
    ctx = payload['contexts']['5A']
    out = {}
    for role in ('ExteriorWall', 'ExteriorRoof', 'ExteriorWindow'):
        rules = [r for r in ctx['components'].get(role, []) if r['when']['scope'] == 'building_default' and not r.get('override')]
        if not rules:
            out[role] = None
            continue
        a = payload['assemblies'][rules[0]['assembly']]
        if a['model'] == 'opaque_layers':
            out[role] = f"{a['metrics']['layer_conductance_W_m2_K']:.3f}"
        else:
            m = payload['materials'][a['layers'][0]['material_id']]['properties']
            out[role] = f"U {m.get('u_W_m2_K', 0):.2f} / SHGC {m.get('shgc', 0):.2f}" if 'u_W_m2_K' in m else 'detailed glazing'
    out['wwr'] = ctx['fenestration']['value']['all']
    return out


def fmt(v, scale=1.0):
    return '–' if v is None else f'{v*scale:.2f}'


def build():
    reference = ninety_one()
    lines = ['# IECC commercial prototypes and the 90.1 templates (evidence only)', '',
             'Generated by `python -m scripts.iecc_commercial_review` from the committed IECC definition inputs '
             '(`data/program-inputs/iecc-commercial-<year>.json`) and release 1.2.0. This report is evidence for '
             '[ADR 0040](../adr/0040-iecc-commercial-family.md) item 11: the IECC family is separate from 90.1, and '
             'nothing here pairs editions or shares records. Editions are set side by side by vintage only.', '',
             '- **Densities** are whole-building means over the counted IECC zones, both families weighted by the '
             'IECC zone floor areas of the same space types. 90.1 lighting includes additional lighting; filled 90.1 '
             'values are used where the source is unknown. A dash: the space type has no 90.1 program of that name.',
             '- **Envelope** is the 5A (Buffalo) context: layer conductance without films (W/m²K) of the area-dominant '
             'exterior wall and roof, window U (W/m²K) and SHGC, and the whole-building window-to-wall ratio over true '
             'outdoor walls (north, east, south, west).', '']
    for edition, ninety in PAIRS:
        document = load_json(ROOT/f'data/program-inputs/iecc-commercial-{edition}.json')
        programs = defaultdict(list)
        for p in document['programs']:
            if p['derivation'] != 'composed':
                programs[p['building_type']].append(p)
        lines += [f'## IECC {edition} and {ninety}', '',
                  '| Type | LPD IECC | LPD 90.1 | EPD IECC | EPD 90.1 | Occ. IECC | Occ. 90.1 | Wall | Roof | Window | WWR N/E/S/W |',
                  '| --- | ---: | ---: | ---: | ---: | ---: | ---: | --- | --- | --- | --- |']
        for building_type in sorted(TYPES.values()):
            ps = programs[building_type]

            def iecc(p):
                values = {l['quantity']: l['value'] for l in p['loads']}
                values['lighting'] = values['lighting'] + values.get('additional_lighting', 0.0)
                return values
            row = [building_type]
            for quantity, _ in QUANTITIES:
                scale = 100.0 if quantity == 'occupancy' else 1.0
                row.append(fmt(weighted(ps, iecc, quantity), scale))
                row.append(fmt(weighted(ps, lambda p: reference.get((ninety, building_type, p['name']), {}), quantity), scale))
            env = envelope(document['envelope'][building_type])
            wwr = env['wwr']
            row += [env['ExteriorWall'] or '–', env['ExteriorRoof'] or '–', env['ExteriorWindow'] or '–',
                    '/'.join('–' if wwr[d] is None else f'{wwr[d]:.2f}' for d in 'NESW')]
            lines.append('| ' + ' | '.join(row) + ' |')
        lines.append('')
    lines += ['## Climate dependence', '',
              'Loads that differ by location within an edition (stored as `value_by_climate`, plan C6):', '']
    for edition in ('2006', '2009', '2012', '2015', '2018', '2021'):
        document = load_json(ROOT/f'data/program-inputs/iecc-commercial-{edition}.json')
        varying = sorted({(p['building_type'], l['quantity']) for p in document['programs'] if p['derivation'] != 'composed'
                          for l in p['loads'] if l.get('value_by_climate')})
        windows = sorted({p['building_type'] for p in document['programs'] if p.get('fenestration', {}).get('value_by_climate')})
        text = ', '.join(f'{t} {q}' for t, q in varying) or 'none'
        lines.append(f'- **IECC {edition}:** {text}.' + (f' Window ratios by climate: {", ".join(windows)}.' if windows else ''))
    lines.append('')
    return '\n'.join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    text = build()
    if args.check:
        if OUTPUT.read_text(encoding='utf-8') != text:
            raise SystemExit(f'{OUTPUT.relative_to(ROOT)} does not reproduce; run python -m scripts.iecc_commercial_review')
        print('IECC review reproduces')
        return
    OUTPUT.write_text(text, encoding='utf-8', newline='\n')
    print(f'Wrote {OUTPUT.relative_to(ROOT)}')


if __name__ == '__main__':
    main()
